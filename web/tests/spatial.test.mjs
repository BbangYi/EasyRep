import assert from 'node:assert/strict';
import { build } from 'esbuild';
const compiled = await build({stdin:{contents:'export * from "./standalone/spatial-data.ts"; export * from "./standalone/spatial-temperature-profile.ts"',resolveDir:process.cwd(),loader:'ts'},bundle:true,write:false,platform:'node',format:'esm'});
const { spatialReadings, interpolateTemperature, spatialHistory, projectPoint, temperatureProfile, temperatureColor } = await import('data:text/javascript;base64,'+Buffer.from(compiled.outputFiles[0].text).toString('base64'));
const layout={dimensionsCm:[20,20,30],geometryRevision:1,placementRevision:1,sensors:[{id:'T1',positionCm:[10,10,28]},{id:'T2',positionCm:[2,2,8]},{id:'T3',positionCm:[18,18,8]}]};
const readings={T1:{value:24,quality:'valid'},T2:{value:20,quality:'valid'},T3:{value:22,quality:'valid'}};
const sensors=spatialReadings(layout,readings);
assert.equal(interpolateTemperature([10,10,28],sensors),24);
assert.equal(interpolateTemperature([10,10,8],sensors.filter(s=>s.id!=='T1')),21);
assert.equal(interpolateTemperature([0,0,0],[]),null);
assert.equal(spatialReadings(layout,{...readings,T1:{value:null,quality:'crc_error'},T2:{value:Infinity,quality:'valid'}}).length,1);
assert.ok(interpolateTemperature([0,0,0],sensors)>=20 && interpolateTemperature([0,0,0],sensors)<=24);
const point={id:'a',at:'2026-10-25T01:00:00Z',data_source:'sensor',geometry_revision:1,placement_revision:1,readings};
assert.deepEqual(spatialHistory([point,{...point,id:'simulation',data_source:'simulation'},{...point,id:'new-layout',placement_revision:2},{...point,id:'bad-date',at:'bad'}],layout).map(p=>p.id),['a']);
const center=projectPoint([10,10,15],layout.dimensionsCm,0.5,0.3);
assert.ok(Math.abs(center.x)<1e-9 && Math.abs(center.y)<1e-9);
assert.ok(projectPoint([10,10,30],layout.dimensionsCm,0,0).y<0);
const nightProfile=temperatureProfile('크레스티드 게코','2026-11-25T12:00:00Z');
assert.deepEqual(nightProfile.range,[18,30]);
assert.equal(nightProfile.label,'야간 기준 20–22°C');
assert.equal(temperatureColor(21,nightProfile.range,nightProfile.stops),'58,121,86');
const dayProfile=temperatureProfile('Crested Gecko','2026-11-25T03:00:00Z');
assert.equal(dayProfile.label,'주간 일반 구역 22–25°C');
assert.equal(temperatureProfile('레오파드 게코','2026-11-25T03:00:00Z'),null);
console.log('Spatial checks passed: sensor anchors, interpolation bounds, invalid readings, provenance/revisions, projection.');
